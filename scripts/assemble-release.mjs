#!/usr/bin/env node
/**
 * Assemble the tree published to the `release` branch: every app in w6w-pack.json as a
 * single bundled file with no npm dependencies, which `github:cohostvip/cohost-w6w@release`
 * can import.
 *
 * w6w refuses to load a source app whose package.json declares dependencies of any kind
 * (`npm_dependencies_forbidden`), and it runs `w6w.entry` as is, so `main` here cannot be
 * imported. Each app in the output has:
 *
 *   <path>/package.json   identity fields and the `w6w` block, `w6w.entry` -> ./app.js
 *   <path>/app.js         the esbuild bundle
 *   <path>/assets/        the icons `w6w.appearance` refers to
 *
 * Usage: node scripts/assemble-release.mjs [--out release-out]
 *
 * Run `npm ci` in each app first. This script runs each app's build itself, with
 * COHOST_API_URL removed, so a local Cohost URL can never reach the release.
 */
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PACKAGE_FIELDS = ["name", "version", "description", "license", "author", "keywords", "type"];

function fail(message) {
  console.error(`assemble-release: ${message}`);
  process.exit(2);
}

let out = join(ROOT, "release-out");
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === "-o" || argv[i] === "--out") out = resolve(argv[++i]);
  else fail(`unknown argument: ${argv[i]}`);
}

const { COHOST_API_URL: _ignored, ...buildEnv } = process.env;
const pack = JSON.parse(readFileSync(join(ROOT, "w6w-pack.json"), "utf8"));

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

for (const { path } of pack.apps) {
  const appDir = resolve(ROOT, path);
  const target = join(out, path);
  const pkg = JSON.parse(readFileSync(join(appDir, "package.json"), "utf8"));

  const built = spawnSync("npm", ["run", "build"], { cwd: appDir, env: buildEnv, stdio: "inherit" });
  if (built.status !== 0) fail(`build failed for ${path}`);

  const bundle = readFileSync(join(appDir, "dist", "app.js"), "utf8");
  if (/^\s*(import|export\s+\*)\s.*["'][^."'][^"']*["']/m.test(bundle)) {
    fail(`${path}: bundle still imports a package, so it would not load on its own`);
  }

  mkdirSync(target, { recursive: true });
  writeFileSync(join(target, "app.js"), bundle);
  if (existsSync(join(appDir, "assets"))) {
    cpSync(join(appDir, "assets"), join(target, "assets"), { recursive: true });
  }

  const release = Object.fromEntries(
    PACKAGE_FIELDS.filter((field) => field in pkg).map((field) => [field, pkg[field]]),
  );
  release.main = "./app.js";
  release.w6w = { ...pkg.w6w, entry: "./app.js" };
  writeFileSync(join(target, "package.json"), `${JSON.stringify(release, null, 2)}\n`);
}

cpSync(join(ROOT, "w6w-pack.json"), join(out, "w6w-pack.json"));
cpSync(join(ROOT, "LICENSE"), join(out, "LICENSE"));
writeFileSync(
  join(out, "README.md"),
  "# cohost-w6w release\n\nGenerated by CI from `main`. Do not edit this branch: each commit " +
    "message names its source commit.\n",
);

console.log(`assembled ${pack.apps.length} apps into ${out}`);
